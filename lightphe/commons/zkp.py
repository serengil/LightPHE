# built-in dependencies
import hashlib
import json
import math
import random
from typing import Any, List, Union

# 3rd party dependencies
from lightecc import LightECC as ECC
from lightecc.interfaces.elliptic_curve import EllipticCurvePoint

# Zero-knowledge proofs are made non-interactive with Fiat-Shamir heuristic.
# Challenge is the hash of everything the verifier sees, so the prover cannot pick it.
# Ref: Fiat & Shamir, "How to prove yourself", 1986
# Ref: Chaum & Pedersen, "Wallet databases with observers", 1992

# pylint: disable=too-few-public-methods, too-many-arguments, too-many-locals

# challenge length of proofs in groups of unknown order in bits
CHALLENGE_BITS = 128

Element = Union[int, EllipticCurvePoint]


def canonicalize(item: Any) -> Any:
    """
    Convert an item into a json serializable form that does not change after
        a json round trip, e.g. tuples and lists are both mapped to lists.
    Args:
        item (any): int, str, tuple, list, dict or elliptic curve point
    Returns:
        canonical form of the item
    """
    if isinstance(item, EllipticCurvePoint):
        return canonicalize(item.get_point())
    if isinstance(item, (tuple, list)):
        return [canonicalize(i) for i in item]
    if isinstance(item, dict):
        return {str(key): canonicalize(value) for key, value in item.items()}
    if isinstance(item, float):
        # identity element of some elliptic curve forms is (inf, inf)
        return str(item)
    return item


def challenge(domain: str, modulo: int, *items: Any) -> int:
    """
    Fiat-Shamir challenge as the hash of a domain and all public items of a proof
    Args:
        domain (str): separates challenges of different proofs
        modulo (int): challenge is reduced in this modulo, e.g. order of the group
        items (any): public items of the proof
    Returns:
        challenge (int)
    """
    transcript = json.dumps([domain, canonicalize(list(items))], separators=(",", ":"))
    digest = hashlib.sha512(transcript.encode("utf-8")).digest()
    return int.from_bytes(digest, "big") % modulo


class PrimeOrderGroup:
    """
    Interface of a cyclic group of a known prime order q used in proofs
    """

    q: int

    def exp(self, base: Element, k: int) -> Element:
        raise NotImplementedError

    def mul(self, a: Element, b: Element) -> Element:
        raise NotImplementedError

    def is_member(self, a: Element) -> bool:
        raise NotImplementedError

    def encode(self, a: Element) -> Any:
        raise NotImplementedError


class ModularGroup(PrimeOrderGroup):
    """
    Subgroup of prime order q in the multiplicative group of integers modulo prime p
    """

    def __init__(self, p: int, q: int):
        self.p = p
        self.q = q

    def exp(self, base: int, k: int) -> int:
        return pow(base, k % self.q, self.p)

    def mul(self, a: int, b: int) -> int:
        return (a * b) % self.p

    def is_member(self, a: int) -> bool:
        return isinstance(a, int) and 0 < a < self.p and pow(a, self.q, self.p) == 1

    def encode(self, a: int) -> int:
        return a


class EllipticCurveGroup(PrimeOrderGroup):
    """
    Subgroup generated by the base point of an elliptic curve. Group operation is
        written multiplicatively here, i.e. exp is scalar multiplication and mul is addition.
    """

    def __init__(self, ecc: ECC):
        self.ecc = ecc
        self.q = ecc.n

    def exp(self, base: EllipticCurvePoint, k: int) -> EllipticCurvePoint:
        return base * (k % self.q)

    def mul(self, a: EllipticCurvePoint, b: EllipticCurvePoint) -> EllipticCurvePoint:
        return a + b

    def is_member(self, a: EllipticCurvePoint) -> bool:
        return isinstance(a, EllipticCurvePoint) and (a * self.q).is_identity()

    def encode(self, a: EllipticCurvePoint) -> Any:
        return a.get_point()


def prove_dleq(
    group: PrimeOrderGroup,
    g1: Element,
    h1: Element,
    g2: Element,
    h2: Element,
    x: int,
    domain: str,
    context: Any = None,
) -> dict:
    """
    Chaum-Pedersen proof that log_g1(h1) = log_g2(h2) = x without revealing x
    Args:
        group (PrimeOrderGroup): group of the elements
        g1, h1, g2, h2 (group elements): h1 = g1^x and h2 = g2^x
        x (int): the common discrete logarithm known by the prover
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenge and response
    """
    w = random.randint(1, group.q - 1)
    a1 = group.exp(g1, w)
    a2 = group.exp(g2, w)
    e = challenge(
        domain,
        group.q,
        context,
        *[group.encode(element) for element in [g1, h1, g2, h2, a1, a2]],
    )
    z = (w + e * x) % group.q
    return {"challenge": e, "response": z}


def verify_dleq(
    group: PrimeOrderGroup,
    g1: Element,
    h1: Element,
    g2: Element,
    h2: Element,
    proof: dict,
    domain: str,
    context: Any = None,
) -> bool:
    """
    Verify a Chaum-Pedersen proof that log_g1(h1) = log_g2(h2)
    Args:
        group (PrimeOrderGroup): group of the elements
        g1, h1, g2, h2 (group elements): public elements of the statement
        proof (dict): output of prove_dleq
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    e = proof.get("challenge")
    z = proof.get("response")
    if not isinstance(e, int) or not isinstance(z, int):
        return False
    if not 0 <= e < group.q or not 0 <= z < group.q:
        return False

    # soundness requires all elements to be in the group of prime order
    if not all(group.is_member(element) for element in [g1, h1, g2, h2]):
        return False

    # a = g^z * h^(-e) is the commitment of an honest prover
    a1 = group.mul(group.exp(g1, z), group.exp(h1, -e))
    a2 = group.mul(group.exp(g2, z), group.exp(h2, -e))
    return e == challenge(
        domain,
        group.q,
        context,
        *[group.encode(element) for element in [g1, h1, g2, h2, a1, a2]],
    )


def prove_paillier_decryption(ciphertext: int, plaintext: int, n: int, phi: int) -> dict:
    """
    Proof of correct decryption for Paillier and Damgard-Jurik. A ciphertext is
        g^m * r^n mod n^2, and this is one to one for m in Z_n and r in Z*_n.
        So, revealing r proves m without a zero-knowledge proof. Only the private key
        owner can recover r. It reveals nothing about other ciphertexts.
    Args:
        ciphertext (int): encrypted message
        plaintext (int): restored message in modulo n
        n (int): public modulus
        phi (int): euler's totient of n
    Returns:
        proof (dict): randomness r of the ciphertext in Z*_n
    """
    n2 = n * n
    if math.gcd(n, phi) != 1:
        raise ValueError("Randomness cannot be recovered because gcd(n, phi) != 1")
    # c * g^-m = r^n mod n^2, and r^n mod n is enough to find r mod n
    r_n = (ciphertext * pow(1 + n, -plaintext, n2)) % n
    return {"randomness": pow(r_n, pow(n, -1, phi), n)}


def verify_paillier_decryption(ciphertext: int, plaintext: int, proof: dict, n: int) -> bool:
    """
    Verify a proof of correct decryption for Paillier and Damgard-Jurik
    Args:
        ciphertext (int): encrypted message
        plaintext (int): claimed message in modulo n
        proof (dict): output of prove_paillier_decryption
        n (int): public modulus
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict) or not isinstance(plaintext, int):
        return False
    r = proof.get("randomness")
    if not isinstance(r, int) or not isinstance(ciphertext, int):
        return False
    if not 0 < r < n or math.gcd(r, n) != 1 or math.gcd(ciphertext, n) != 1:
        return False
    if not 0 <= plaintext < n:
        return False
    n2 = n * n
    return ciphertext % n2 == (pow(1 + n, plaintext, n2) * pow(r, n, n2)) % n2


def prove_dleq_or(
    group: PrimeOrderGroup,
    g1: Element,
    h1: Element,
    g2: Element,
    h2s: List[Element],
    x: int,
    index: int,
    domain: str,
    context: Any = None,
) -> dict:
    """
    Disjunctive Chaum-Pedersen proof that log_g1(h1) = log_g2(h2) for at least one
        h2 in h2s, without revealing which one. Proofs of other items are simulated.
    Args:
        group (PrimeOrderGroup): group of the elements
        g1, h1, g2 (group elements): h1 = g1^x
        h2s (list of group elements): h2s[index] = g2^x
        x (int): the common discrete logarithm known by the prover
        index (int): index of the true statement
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenges and responses of all statements
    """
    q = group.q
    challenges: List[int] = []
    responses: List[int] = []
    commitments: List[Element] = []
    w = random.randint(1, q - 1)
    for i, h2 in enumerate(h2s):
        if i == index:
            challenges.append(0)
            responses.append(0)
            commitments += [group.exp(g1, w), group.exp(g2, w)]
            continue
        # simulated proof for a false statement
        e_i = random.randint(0, q - 1)
        z_i = random.randint(0, q - 1)
        challenges.append(e_i)
        responses.append(z_i)
        commitments += [
            group.mul(group.exp(g1, z_i), group.exp(h1, -e_i)),
            group.mul(group.exp(g2, z_i), group.exp(h2, -e_i)),
        ]

    e = challenge(
        domain,
        q,
        context,
        *[group.encode(element) for element in [g1, h1, g2] + list(h2s) + commitments],
    )
    # challenge of the true statement completes the sum
    challenges[index] = (e - sum(challenges)) % q
    responses[index] = (w + challenges[index] * x) % q
    return {"challenges": challenges, "responses": responses}


def verify_dleq_or(
    group: PrimeOrderGroup,
    g1: Element,
    h1: Element,
    g2: Element,
    h2s: List[Element],
    proof: dict,
    domain: str,
    context: Any = None,
) -> bool:
    """
    Verify a disjunctive Chaum-Pedersen proof
    Args:
        group (PrimeOrderGroup): group of the elements
        g1, h1, g2 (group elements): public elements of the statement
        h2s (list of group elements): one of them is claimed to be g2^log_g1(h1)
        proof (dict): output of prove_dleq_or
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    challenges = proof.get("challenges")
    responses = proof.get("responses")
    if not isinstance(challenges, list) or not isinstance(responses, list):
        return False
    if len(challenges) != len(h2s) or len(responses) != len(h2s):
        return False
    q = group.q
    for value in challenges + responses:
        if not isinstance(value, int) or not 0 <= value < q:
            return False

    # soundness requires all elements to be in the group of prime order
    if not all(group.is_member(element) for element in [g1, h1, g2] + list(h2s)):
        return False

    commitments: List[Element] = []
    for h2, e_i, z_i in zip(h2s, challenges, responses):
        commitments += [
            group.mul(group.exp(g1, z_i), group.exp(h1, -e_i)),
            group.mul(group.exp(g2, z_i), group.exp(h2, -e_i)),
        ]

    e = challenge(
        domain,
        q,
        context,
        *[group.encode(element) for element in [g1, h1, g2] + list(h2s) + commitments],
    )
    return sum(challenges) % q == e


def nth_power_challenge_bits(n: int) -> int:
    """
    Challenge length of proofs of n-th powers. Challenges must be smaller than
        the smallest prime factor of n for soundness.
    Args:
        n (int): public modulus
    Returns:
        bits (int)
    """
    return max(1, min(CHALLENGE_BITS, n.bit_length() // 2 - 2))


def random_unit(n: int, modulo: int) -> int:
    """
    Random element of the multiplicative group of the modulo
    Args:
        n (int): public modulus, units are co-prime to it
        modulo (int): a power of n
    Returns:
        unit (int)
    """
    while True:
        r = random.randint(1, modulo - 1)
        if math.gcd(r, n) == 1:
            return r


def prove_nth_power_or(
    n: int,
    modulo: int,
    us: List[int],
    r: int,
    index: int,
    domain: str,
    context: Any = None,
) -> dict:
    """
    Prove that at least one of us is an n-th power in modulo, without revealing which.
        This is the 1-out-of-k proof of Damgard & Jurik, showing that a ciphertext
        c encrypts one of k values v, where us are c * g^-v.
    Args:
        n (int): public modulus
        modulo (int): n^(s+1)
        us (list of int): us[index] = r^n mod modulo
        r (int): n-th root of us[index] known by the prover
        index (int): index of the true statement
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenges and responses of all statements
    """
    bound = 1 << nth_power_challenge_bits(n)
    challenges: List[int] = []
    responses: List[int] = []
    commitments: List[int] = []
    rho = random_unit(n, modulo)
    for i, u in enumerate(us):
        if i == index:
            challenges.append(0)
            responses.append(0)
            commitments.append(pow(rho, n, modulo))
            continue
        # simulated proof for a false statement
        e_i = random.randint(0, bound - 1)
        z_i = random_unit(n, modulo)
        challenges.append(e_i)
        responses.append(z_i)
        commitments.append((pow(z_i, n, modulo) * pow(u, -e_i, modulo)) % modulo)

    e = challenge(domain, bound, context, n, modulo, us, commitments)
    # challenge of the true statement completes the sum
    challenges[index] = (e - sum(challenges)) % bound
    responses[index] = (rho * pow(r, challenges[index], modulo)) % modulo
    return {"challenges": challenges, "responses": responses}


def verify_nth_power_or(
    n: int,
    modulo: int,
    us: List[int],
    proof: dict,
    domain: str,
    context: Any = None,
) -> bool:
    """
    Verify a proof that at least one of us is an n-th power in modulo
    Args:
        n (int): public modulus
        modulo (int): n^(s+1)
        us (list of int): candidates
        proof (dict): output of prove_nth_power_or
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    challenges = proof.get("challenges")
    responses = proof.get("responses")
    if not isinstance(challenges, list) or not isinstance(responses, list):
        return False
    if len(challenges) != len(us) or len(responses) != len(us):
        return False
    bound = 1 << nth_power_challenge_bits(n)
    for e_i in challenges:
        if not isinstance(e_i, int) or not 0 <= e_i < bound:
            return False
    for value in responses + us:
        if not isinstance(value, int) or not 0 < value < modulo or math.gcd(value, n) != 1:
            return False

    commitments = [
        (pow(z_i, n, modulo) * pow(u, -e_i, modulo)) % modulo
        for u, e_i, z_i in zip(us, challenges, responses)
    ]
    e = challenge(domain, bound, context, n, modulo, us, commitments)
    return sum(challenges) % bound == e


def paillier_membership_candidates(
    ciphertext: int, values: List[int], n: int, modulo: int
) -> List[int]:
    """
    Candidates c * g^-v for each value v. Ciphertext encrypts v if and only if
        its candidate is an n-th power, i.e. an encryption of 0.
    Args:
        ciphertext (int): encrypted message
        values (list of int): allowed values
        n (int): public modulus
        modulo (int): ciphertext modulo n^(s+1)
    Returns:
        candidates (list of int)
    """
    return [(ciphertext * pow(1 + n, -value, modulo)) % modulo for value in values]


def range_weights(width: int) -> List[int]:
    """
    Weights of bits to represent every integer in [0, width] exactly, i.e.
        1, 2, 4, ..., 2^(k-2) and width - (2^(k-1) - 1) where k is the bit length of width.
        Sums of 0/1 bits with these weights cover [0, width], and nothing out of it.
    Args:
        width (int): high - low of the range
    Returns:
        weights (list of int)
    """
    k = width.bit_length()
    if k == 0:
        return []
    return [1 << i for i in range(k - 1)] + [width - ((1 << (k - 1)) - 1)]


def decompose(value: int, weights: List[int]) -> List[int]:
    """
    Find 0/1 bits of a value in [0, sum of weights] for weights of range_weights
    Args:
        value (int): value to decompose
        weights (list of int): output of range_weights
    Returns:
        bits (list of int)
    """
    if not weights:
        return []
    last = int(value >= weights[-1])
    rest = value - last * weights[-1]
    return [(rest >> i) & 1 for i in range(len(weights) - 1)] + [last]


def range_context(context: Any, low: int, high: int, index: int) -> list:
    """
    Context of a part of a range proof. It binds every part to its position and range,
        so parts cannot be reordered or moved into another proof.
    """
    return ["range", low, high, index, context]


def combine_range_ciphertexts(cs: Any, ciphertexts: list, weights: List[int]) -> Any:
    """
    Restore the ciphertext of a range proof homomorphically as c_low + Σ w_i * c_i
    Args:
        cs (Homomorphic): additively homomorphic cryptosystem
        ciphertexts (list): encryption of low and encryptions of bits
        weights (list of int): weights of bits
    Returns:
        ciphertext
    """
    combined = ciphertexts[0]
    for ciphertext, weight in zip(ciphertexts[1:], weights):
        combined = cs.add(combined, cs.multiply_by_constant(ciphertext, weight))
    return combined


def prove_range(
    cs: Any, plaintext: int, low: int, high: int, values: List[int], context: Any = None
) -> tuple:
    """
    Encrypt a plaintext in [low, high] and prove that it is in this range without
        revealing it. It is decomposed into bits, each bit is encrypted with a proof
        that it is 0 or 1, and low is encrypted with a proof that it is low. Ciphertext
        is c_low + Σ w_i * c_i, so anyone can restore it from the parts.
    Args:
        cs (Homomorphic): additively homomorphic cryptosystem supporting encrypt_with_proof
        plaintext (int): message in [low, high]
        low (int): lower bound
        high (int): upper bound
        values (list of int): normalized [low, 0, 1] in plaintext modulo
        context (any): public data bound to the proof
    Returns:
        ciphertext: encrypted plaintext
        proof (dict): ciphertexts of low and bits, and their proofs
    """
    normalized_low, zero, one = values
    weights = range_weights(high - low)
    bits = decompose(plaintext - low, weights)

    ciphertexts = []
    proofs = []
    parts = [(normalized_low, [normalized_low])] + [
        (one if bit == 1 else zero, [zero, one]) for bit in bits
    ]
    for index, (value, allowed) in enumerate(parts):
        ciphertext, proof = cs.encrypt_with_proof(
            plaintext=value, values=allowed, context=range_context(context, low, high, index)
        )
        ciphertexts.append(ciphertext)
        proofs.append(proof)

    ciphertext = combine_range_ciphertexts(cs, ciphertexts, weights)
    return ciphertext, {"ciphertexts": ciphertexts, "proofs": proofs}


def verify_range(
    cs: Any,
    ciphertext: Any,
    proof: dict,
    low: int,
    high: int,
    values: List[int],
    context: Any = None,
) -> bool:
    """
    Verify that a ciphertext encrypts a value in [low, high] with public key only
    Args:
        cs (Homomorphic): additively homomorphic cryptosystem supporting verify_ciphertext
        ciphertext: encrypted message
        proof (dict): output of prove_range
        low (int): lower bound
        high (int): upper bound
        values (list of int): normalized [low, 0, 1] in plaintext modulo
        context (any): public data that the proof is expected to be bound to
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    ciphertexts = proof.get("ciphertexts")
    proofs = proof.get("proofs")
    weights = range_weights(high - low)
    if not isinstance(ciphertexts, list) or not isinstance(proofs, list):
        return False
    if len(ciphertexts) != len(weights) + 1 or len(proofs) != len(weights) + 1:
        return False

    normalized_low, zero, one = values
    for index, (part, part_proof) in enumerate(zip(ciphertexts, proofs)):
        allowed = [normalized_low] if index == 0 else [zero, one]
        if not cs.verify_ciphertext(
            ciphertext=part,
            proof=part_proof,
            values=allowed,
            context=range_context(context, low, high, index),
        ):
            return False

    try:
        combined = combine_range_ciphertexts(cs, ciphertexts, weights)
    except Exception:  # pylint: disable=broad-except
        # malformed parts raise errors of the cryptosystem
        return False
    return canonicalize(combined) == canonicalize(ciphertext)


def prove_dlog(
    group: PrimeOrderGroup, g: Element, h: Element, x: int, domain: str, context: Any = None
) -> dict:
    """
    Schnorr proof of knowledge of x = log_g(h) without revealing x
    Args:
        group (PrimeOrderGroup): group of the elements
        g, h (group elements): h = g^x
        x (int): discrete logarithm known by the prover
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenge and response
    """
    w = random.randint(1, group.q - 1)
    a = group.exp(g, w)
    e = challenge(domain, group.q, context, group.encode(g), group.encode(h), group.encode(a))
    return {"challenge": e, "response": (w + e * x) % group.q}


def verify_dlog(
    group: PrimeOrderGroup, g: Element, h: Element, proof: dict, domain: str, context: Any = None
) -> bool:
    """
    Verify a Schnorr proof of knowledge of log_g(h)
    Args:
        group (PrimeOrderGroup): group of the elements
        g, h (group elements): public elements of the statement
        proof (dict): output of prove_dlog
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    e = proof.get("challenge")
    z = proof.get("response")
    if not isinstance(e, int) or not isinstance(z, int):
        return False
    if not 0 <= e < group.q or not 0 <= z < group.q:
        return False
    if not group.is_member(g) or not group.is_member(h):
        return False

    # a = g^z * h^(-e) is the commitment of an honest prover
    a = group.mul(group.exp(g, z), group.exp(h, -e))
    return e == challenge(domain, group.q, context, group.encode(g), group.encode(h), group.encode(a))


def prove_paillier_knowledge(
    ciphertext: int,
    plaintext: int,
    r: int,
    n: int,
    modulo: int,
    domain: str,
    context: Any = None,
) -> dict:
    """
    Proof of knowledge of plaintext m and randomness r of a Paillier or Damgard-Jurik
        ciphertext c = g^m * r^n mod n^(s+1), without revealing them
    Args:
        ciphertext (int): encrypted message
        plaintext (int): m known by the prover
        r (int): randomness known by the prover
        n (int): public modulus
        modulo (int): ciphertext modulo n^(s+1)
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenge and responses
    """
    g = 1 + n
    bound = 1 << nth_power_challenge_bits(n)
    a = random.randint(0, n - 1)
    b = random_unit(n, modulo)
    t = (pow(g, a, modulo) * pow(b, n, modulo)) % modulo
    e = challenge(domain, bound, context, n, modulo, ciphertext, t)

    # a + e * m = z_m + carry * n, and g^(carry * n) is moved into the n-th power
    carry, z_m = divmod(a + e * plaintext, n)
    z_r = (b * pow(r, e, modulo) * pow(g, carry, modulo)) % modulo
    return {"challenge": e, "plaintext_response": z_m, "randomness_response": z_r}


def verify_paillier_knowledge(
    ciphertext: int, proof: dict, n: int, modulo: int, domain: str, context: Any = None
) -> bool:
    """
    Verify a proof of knowledge of plaintext and randomness of a Paillier or
        Damgard-Jurik ciphertext
    Args:
        ciphertext (int): encrypted message
        proof (dict): output of prove_paillier_knowledge
        n (int): public modulus
        modulo (int): ciphertext modulo n^(s+1)
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    e = proof.get("challenge")
    z_m = proof.get("plaintext_response")
    z_r = proof.get("randomness_response")
    if not all(isinstance(value, int) for value in [ciphertext, e, z_m, z_r]):
        return False
    if not 0 <= e < (1 << nth_power_challenge_bits(n)) or not 0 <= z_m < n:
        return False
    for value in [ciphertext, z_r]:
        if not 0 < value < modulo or math.gcd(value, n) != 1:
            return False

    # t = g^z_m * z_r^n * c^-e is the commitment of an honest prover
    g = 1 + n
    t = (pow(g, z_m, modulo) * pow(z_r, n, modulo) * pow(ciphertext, -e, modulo)) % modulo
    return e == challenge(
        domain, 1 << nth_power_challenge_bits(n), context, n, modulo, ciphertext, t
    )


# statistical hiding of responses in groups of unknown order, in bits
STATISTICAL_BITS = 80


def dleq_unknown_order_bits(n: int, modulo: int, x_bits: int) -> int:
    """
    Bit length of random values of proofs in groups of unknown order, so that responses
        hide the secret statistically
    Args:
        n (int): public modulus
        modulo (int): n^(s+1)
        x_bits (int): upper bound of the bit length of the secret
    Returns:
        bits (int)
    """
    return max(modulo.bit_length(), x_bits) + nth_power_challenge_bits(n) + STATISTICAL_BITS


def prove_dleq_unknown_order(
    n: int,
    modulo: int,
    g1: int,
    h1: int,
    g2: int,
    h2: int,
    x: int,
    x_bits: int,
    domain: str,
    context: Any = None,
) -> dict:
    """
    Proof that log_g1(h1) = log_g2(h2) = x in the group of squares modulo n^(s+1), whose
        order is secret. Response is computed over the integers and hides x statistically.
        This is the proof of correct partial decryption of Shoup and Damgard-Jurik.
    Args:
        n (int): public modulus, product of two safe primes
        modulo (int): n^(s+1)
        g1, h1, g2, h2 (int): squares modulo n^(s+1) with h1 = g1^x and h2 = g2^x
        x (int): the common discrete logarithm known by the prover
        x_bits (int): upper bound of the bit length of x
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        proof (dict): challenge and response
    """
    w = random.getrandbits(dleq_unknown_order_bits(n, modulo, x_bits))
    a1 = pow(g1, w, modulo)
    a2 = pow(g2, w, modulo)
    e = challenge(domain, 1 << nth_power_challenge_bits(n), context, modulo, g1, h1, g2, h2, a1, a2)
    return {"challenge": e, "response": w + e * x}


def verify_dleq_unknown_order(
    n: int,
    modulo: int,
    g1: int,
    h1: int,
    g2: int,
    h2: int,
    proof: dict,
    x_bits: int,
    domain: str,
    context: Any = None,
) -> bool:
    """
    Verify a proof that log_g1(h1) = log_g2(h2) in the group of squares modulo n^(s+1)
    Args:
        n (int): public modulus, product of two safe primes
        modulo (int): n^(s+1)
        g1, h1, g2, h2 (int): public elements of the statement
        proof (dict): output of prove_dleq_unknown_order
        x_bits (int): upper bound of the bit length of the secret
        domain (str): name of the statement being proven
        context (any): extra public data bound to the proof
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict):
        return False
    e = proof.get("challenge")
    z = proof.get("response")
    if not isinstance(e, int) or not isinstance(z, int):
        return False
    if not 0 <= e < (1 << nth_power_challenge_bits(n)):
        return False
    if not 0 <= z < (1 << (dleq_unknown_order_bits(n, modulo, x_bits) + 1)):
        return False
    for element in [g1, h1, g2, h2]:
        if not isinstance(element, int) or not 0 < element < modulo or math.gcd(element, n) != 1:
            return False

    # a = g^z * h^(-e) is the commitment of an honest prover
    a1 = (pow(g1, z, modulo) * pow(h1, -e, modulo)) % modulo
    a2 = (pow(g2, z, modulo) * pow(h2, -e, modulo)) % modulo
    return e == challenge(
        domain, 1 << nth_power_challenge_bits(n), context, modulo, g1, h1, g2, h2, a1, a2
    )


def one_hot_context(context: Any, options: int, slot: Any) -> list:
    """
    Context of a part of a one-hot proof. It binds every slot to its position and the
        number of options, so slots cannot be reordered or moved into another ballot.
    """
    return ["one-hot", options, slot, context]


def prove_one_hot(cs: Any, choice: int, options: int, values: List[int], context: Any = None) -> tuple:
    """
    Encrypt a one-hot vector, i.e. 1 for the chosen option and 0 for others, and prove
        that each slot is 0 or 1 and that slots sum to 1 without revealing the choice.
    Args:
        cs (Homomorphic): additively homomorphic cryptosystem supporting prove_membership
        choice (int): index of the chosen option
        options (int): number of options
        values (list of int): normalized [0, 1] in plaintext modulo
        context (any): public data bound to the proof
    Returns:
        ciphertexts (list): encrypted slots
        proof (dict): proofs of slots and their sum
    """
    zero, one = values
    ciphertexts = []
    random_keys = []
    slot_proofs = []
    for slot in range(options):
        plaintext = one if slot == choice else zero
        random_key = cs.generate_random_key()
        ciphertext = cs.encrypt(plaintext=plaintext, random_key=random_key)
        slot_proofs.append(
            cs.prove_membership(
                ciphertext=ciphertext,
                plaintext=plaintext,
                random_key=random_key,
                values=[zero, one],
                context=one_hot_context(context, options, slot),
            )
        )
        ciphertexts.append(ciphertext)
        random_keys.append(random_key)

    # sum of slots encrypts 1, and its random key is combined from random keys of slots
    total = ciphertexts[0]
    for ciphertext in ciphertexts[1:]:
        total = cs.add(total, ciphertext)
    sum_proof = cs.prove_membership(
        ciphertext=total,
        plaintext=one,
        random_key=cs.combine_random_keys(random_keys),
        values=[one],
        context=one_hot_context(context, options, "sum"),
    )
    return ciphertexts, {"slots": slot_proofs, "sum": sum_proof}


def verify_one_hot(cs: Any, ciphertexts: list, proof: dict, values: List[int], context: Any = None) -> bool:
    """
    Verify that encrypted slots are a one-hot vector with public key only
    Args:
        cs (Homomorphic): additively homomorphic cryptosystem supporting verify_ciphertext
        ciphertexts (list): encrypted slots
        proof (dict): output of prove_one_hot
        values (list of int): normalized [0, 1] in plaintext modulo
        context (any): public data that the proof is expected to be bound to
    Returns:
        is valid (bool)
    """
    if not isinstance(proof, dict) or not isinstance(ciphertexts, list) or not ciphertexts:
        return False
    slot_proofs = proof.get("slots")
    if not isinstance(slot_proofs, list) or len(slot_proofs) != len(ciphertexts):
        return False
    options = len(ciphertexts)
    zero, one = values

    for slot, (ciphertext, slot_proof) in enumerate(zip(ciphertexts, slot_proofs)):
        if not cs.verify_ciphertext(
            ciphertext=ciphertext,
            proof=slot_proof,
            values=[zero, one],
            context=one_hot_context(context, options, slot),
        ):
            return False

    try:
        total = ciphertexts[0]
        for ciphertext in ciphertexts[1:]:
            total = cs.add(total, ciphertext)
    except Exception:  # pylint: disable=broad-except
        # malformed slots raise errors of the cryptosystem
        return False
    return cs.verify_ciphertext(
        ciphertext=total,
        proof=proof.get("sum"),
        values=[one],
        context=one_hot_context(context, options, "sum"),
    )
